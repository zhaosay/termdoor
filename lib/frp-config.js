// The frpc config that TermDoor writes for the "frp" dialog.
//
// The file is generated from a handful of validated fields and never from text
// the page sends: frp configs can add proxies and plugins that would expose
// files or a shell, so letting a request smuggle in extra TOML would be a hole.
// The token is the only copy of the secret; it is never sent back to the page.
const fs = require('fs');
const path = require('path');
const { DATA_DIR, FRPC_CONFIG_FILE, REMOTE_PORT } = require('./config');

const HOST_RE = /^(?=.{1,253}$)[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?(?:\.[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?)*$/;
const NAME_RE = /^[A-Za-z0-9_-]{1,40}$/;
const TOKEN_RE = /^[A-Za-z0-9._~+/=-]{8,128}$/;

function toPort(v) {
  if (typeof v === 'string' && /^\d{1,5}$/.test(v)) v = Number(v);
  return Number.isInteger(v) && v >= 1 && v <= 65535 ? v : null;
}

function load() {
  let text;
  try { text = fs.readFileSync(FRPC_CONFIG_FILE, 'utf8'); } catch { return null; }
  const str = (re) => { const m = text.match(re); return m ? m[1] : null; };
  const num = (re) => { const m = text.match(re); return m ? Number(m[1]) : null; };
  return {
    serverAddr: str(/^serverAddr = "([^"]*)"/m),
    serverPort: num(/^serverPort = (\d+)/m),
    token: str(/^auth\.token = "([^"]*)"/m),
    remotePort: num(/^remotePort = (\d+)/m),
    proxyName: str(/^name = "([^"]*)"/m),
  };
}

// What the page may see: everything except the token itself.
function status() {
  const cur = load();
  return {
    configured: !!(cur && cur.serverAddr && cur.token),
    serverAddr: cur ? cur.serverAddr : null,
    serverPort: cur ? cur.serverPort : null,
    remotePort: cur ? cur.remotePort : null,
    proxyName: cur ? cur.proxyName : null,
    hasToken: !!(cur && cur.token),
    remoteListenerPort: REMOTE_PORT,
    configPath: FRPC_CONFIG_FILE,
  };
}

function render(v) {
  const q = JSON.stringify;
  return [
    '# Generated by TermDoor (settings > frp). Change it there, not by hand.',
    `serverAddr = ${q(v.serverAddr)}`,
    `serverPort = ${v.serverPort}`,
    'auth.method = "token"',
    `auth.token = ${q(v.token)}`,
    `log.to = ${q(path.join(DATA_DIR, 'frpc.log'))}`,
    'log.level = "info"',
    'log.maxDays = 7',
    '',
    '[[proxies]]',
    `name = ${q(v.proxyName)}`,
    'type = "tcp"',
    'localIP = "127.0.0.1"',
    // always TermDoor's own remote port (the one that demands the secondary key),
    // never a value the page can choose
    `localPort = ${REMOTE_PORT}`,
    `remotePort = ${v.remotePort}`,
    '',
  ].join('\n');
}

function writePrivate(file, text) {
  const tmp = `${file}.tmp-${process.pid}`;
  try { fs.unlinkSync(tmp); } catch {}
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(tmp, text, { mode: 0o600 });
  fs.renameSync(tmp, file);
}

// -> { ok: true } | { ok: false, error: '<short code>' }. Nothing is written on error.
function save(input) {
  if (REMOTE_PORT === null) return { ok: false, error: 'remote port not configured' };
  if (!input || typeof input !== 'object' || Array.isArray(input)) return { ok: false, error: 'invalid body' };

  const serverAddr = typeof input.serverAddr === 'string' ? input.serverAddr.trim() : '';
  if (!HOST_RE.test(serverAddr)) return { ok: false, error: 'invalid serverAddr' };

  const serverPort = toPort(input.serverPort === undefined || input.serverPort === '' ? 7000 : input.serverPort);
  if (serverPort === null) return { ok: false, error: 'invalid serverPort' };

  const remotePort = toPort(input.remotePort);
  if (remotePort === null) return { ok: false, error: 'invalid remotePort' };

  const rawName = typeof input.proxyName === 'string' ? input.proxyName.trim() : '';
  const proxyName = rawName === '' ? 'termdoor' : rawName;
  if (!NAME_RE.test(proxyName)) return { ok: false, error: 'invalid proxyName' };

  let token;
  if (typeof input.token === 'string' && input.token !== '') {
    token = input.token;
    if (!TOKEN_RE.test(token)) return { ok: false, error: 'invalid token' };
  } else {
    const cur = load();
    token = cur && cur.token;
    if (!token) return { ok: false, error: 'token required' };
  }

  writePrivate(FRPC_CONFIG_FILE, render({ serverAddr, serverPort, token, remotePort, proxyName }));
  return { ok: true };
}

function remove() {
  try { fs.unlinkSync(FRPC_CONFIG_FILE); } catch {}
}

module.exports = { status, save, remove, load, render };
